/**
 * Browser-session idempotency for potentially billable Creator submissions.
 * An accepted provider submission is NOT permission to mint a fresh key.
 * Repeat clicks / retries with identical inputs must return the original job.
 * Changing the payload is a new, separately priced user intent.
 */
export type CreatorRequestIntent = { key: string; fingerprint: string; keysByFingerprint?: Record<string, string> };

export function creatorIntentKey(
  intents: Record<string, CreatorRequestIntent>,
  scope: string,
  payload: unknown,
  newKey: () => string,
): string {
  const fingerprint = JSON.stringify(payload);
  const previous = intents[scope];
  if (previous?.fingerprint === fingerprint) return previous.key;
  // Keep all requests seen for this scope, not just the immediately previous one.
  // A -> B -> A must reuse A's original job instead of silently spending again.
  const keysByFingerprint = previous?.keysByFingerprint ?? Object.create(null) as Record<string, string>;
  if (previous) keysByFingerprint[previous.fingerprint] = previous.key;
  const key = Object.prototype.hasOwnProperty.call(keysByFingerprint, fingerprint)
    ? keysByFingerprint[fingerprint]
    : newKey();
  keysByFingerprint[fingerprint] = key;
  intents[scope] = { key, fingerprint, keysByFingerprint };
  return key;
}

/**
 * Same-tab reload-safe identity for paid requests. The stored lookup is a
 * SHA-256 digest, not raw prompt, speech text, or avatar-consent data.
 *
 * Fail closed if tab storage cannot be read/written: using a new UUID after
 * losing the old mapping could submit a second chargeable provider request.
 * This does not promise cross-device or cross-tab deduplication.
 */
export async function creatorPersistentIntentKey(
  intents: Record<string, CreatorRequestIntent>,
  scope: string,
  payload: unknown,
  newKey: () => string,
  storage: Pick<Storage, "getItem" | "setItem"> = window.sessionStorage,
): Promise<string> {
  const fingerprint = JSON.stringify(payload);
  if (typeof fingerprint !== "string") throw new Error("CREATOR_IDEMPOTENCY_FINGERPRINT_INVALID");
  if (!globalThis.crypto?.subtle) throw new Error("CREATOR_IDEMPOTENCY_STORAGE_UNAVAILABLE");

  const encoded = new TextEncoder().encode(JSON.stringify([scope, fingerprint]));
  const digest = await globalThis.crypto.subtle.digest("SHA-256", encoded);
  const lookup = "sakthiai.creator.intent.v1:" +
    Array.from(new Uint8Array(digest), value => value.toString(16).padStart(2, "0")).join("");

  let saved: string | null;
  try {
    saved = storage.getItem(lookup);
  } catch {
    throw new Error("CREATOR_IDEMPOTENCY_STORAGE_UNAVAILABLE");
  }
  if (saved !== null) {
    // Keys are generated by crypto.randomUUID. Do not accept a corrupted mapping.
    if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(saved)) {
      throw new Error("CREATOR_IDEMPOTENCY_STORAGE_CORRUPT");
    }
    const previous = intents[scope];
    const keysByFingerprint = previous?.keysByFingerprint ?? Object.create(null) as Record<string, string>;
    if (previous) keysByFingerprint[previous.fingerprint] = previous.key;
    keysByFingerprint[fingerprint] = saved;
    intents[scope] = { key: saved, fingerprint, keysByFingerprint };
    return saved;
  }

  const key = creatorIntentKey(intents, scope, payload, newKey);
  try {
    storage.setItem(lookup, key);
  } catch {
    throw new Error("CREATOR_IDEMPOTENCY_STORAGE_UNAVAILABLE");
  }
  return key;
}
